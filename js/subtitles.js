/**
 * VideoForge Pro - AI Subtitles, Speech Recognition & Caption Engine
 */

export const SubtitlesManager = {
  cues: [
    { id: 1, start: 1.2, end: 4.5, text: "Welcome to VideoForge Pro, your all-in-one studio." },
    { id: 2, start: 5.0, end: 8.8, text: "Edit, color grade, and burn captions directly in your browser." },
    { id: 3, start: 9.2, end: 12.6, text: "High performance client-side video composition and audio design." }
  ],
  
  // Style settings
  style: {
    font: 'Instrument Sans',
    size: 20,
    color: '#ffffff',
    backgroundColor: 'rgba(0, 0, 0, 0.82)',
    borderColor: '#e8ff47',
    positionY: 0.88, // 88% down from top
    burnIn: true
  },

  isRecognizing: false,
  recognitionInstance: null,

  getActiveCue(time) {
    return this.cues.find(c => time >= c.start && time <= c.end);
  },

  addCue(start, end, text) {
    const id = Date.now();
    this.cues.push({ id, start, end, text });
    this.cues.sort((a, b) => a.start - b.start);
    return id;
  },

  updateCue(id, newText, newStart, newEnd) {
    const cue = this.cues.find(c => c.id === id);
    if (cue) {
      if (newText !== undefined) cue.text = newText;
      if (newStart !== undefined) cue.start = newStart;
      if (newEnd !== undefined) cue.end = newEnd;
      this.cues.sort((a, b) => a.start - b.start);
    }
  },

  deleteCue(id) {
    this.cues = this.cues.filter(c => c.id !== id);
  },

  /**
   * Browser Web Speech API Live AI Speech-to-Text Transcriber
   */
  startLiveTranscription(onTranscriptChunk, onComplete) {
    const SpeechRecognition = window.SpeechRecognition || window.webkitSpeechRecognition;
    if (!SpeechRecognition) {
      alert("Web Speech API is not supported in this browser. Please use Google Chrome or Microsoft Edge.");
      if (onComplete) onComplete();
      return;
    }

    try {
      this.recognitionInstance = new SpeechRecognition();
      this.recognitionInstance.continuous = true;
      this.recognitionInstance.interimResults = true;
      this.recognitionInstance.lang = 'en-US';

      this.isRecognizing = true;
      let startTime = 0;

      this.recognitionInstance.onstart = () => {
        startTime = Date.now();
      };

      this.recognitionInstance.onresult = (event) => {
        for (let i = event.resultIndex; i < event.results.length; ++i) {
          if (event.results[i].isFinal) {
            const transcript = event.results[i][0].transcript.trim();
            if (transcript) {
              const elapsedSec = (Date.now() - startTime) / 1000;
              this.addCue(Math.max(0, elapsedSec - 3), elapsedSec, transcript);
              if (onTranscriptChunk) onTranscriptChunk(transcript);
            }
          }
        }
      };

      this.recognitionInstance.onerror = (e) => {
        console.warn("Speech recognition notice:", e.error);
      };

      this.recognitionInstance.onend = () => {
        this.isRecognizing = false;
        if (onComplete) onComplete();
      };

      this.recognitionInstance.start();
    } catch (e) {
      console.warn("Speech API start error:", e);
      if (onComplete) onComplete();
    }
  },

  stopLiveTranscription() {
    if (this.recognitionInstance && this.isRecognizing) {
      this.recognitionInstance.stop();
      this.isRecognizing = false;
    }
  },

  /**
   * Generates formatted SRT file content
   */
  exportSRT() {
    let srt = '';
    this.cues.forEach((c, idx) => {
      srt += `${idx + 1}\n`;
      srt += `${this.formatSRTTime(c.start)} --> ${this.formatSRTTime(c.end)}\n`;
      srt += `${c.text}\n\n`;
    });
    this.downloadFile('subtitles.srt', srt, 'text/plain');
  },

  /**
   * Generates formatted VTT file content
   */
  exportVTT() {
    let vtt = 'WEBVTT - Generated by VideoForge Pro\n\n';
    this.cues.forEach((c, idx) => {
      vtt += `${idx + 1}\n`;
      vtt += `${this.formatVTTTime(c.start)} --> ${this.formatVTTTime(c.end)}\n`;
      vtt += `${c.text}\n\n`;
    });
    this.downloadFile('subtitles.vtt', vtt, 'text/vtt');
  },

  /**
   * Parses an imported .srt file string into cues
   */
  importSRT(srtString) {
    const blocks = srtString.trim().split(/\n\s*\n/);
    this.cues = [];
    
    blocks.forEach((b, idx) => {
      const lines = b.split('\n');
      if (lines.length >= 2) {
        const timeLine = lines[1].includes('-->') ? lines[1] : lines[0];
        const textLines = lines.slice(lines.indexOf(timeLine) + 1).join(' ');
        
        const [startStr, endStr] = timeLine.split('-->').map(s => s.trim());
        if (startStr && endStr) {
          const start = this.parseSRTTime(startStr);
          const end = this.parseSRTTime(endStr);
          if (!isNaN(start) && !isNaN(end)) {
            this.cues.push({ id: idx + 1, start, end, text: textLines });
          }
        }
      }
    });
  },

  formatSRTTime(seconds) {
    const h = Math.floor(seconds / 3600);
    const m = Math.floor((seconds % 3600) / 60);
    const s = Math.floor(seconds % 60);
    const ms = Math.floor((seconds % 1) * 1000);
    return `${String(h).padStart(2, '0')}:${String(m).padStart(2, '0')}:${String(s).padStart(2, '0')},${String(ms).padStart(3, '0')}`;
  },

  formatVTTTime(seconds) {
    const h = Math.floor(seconds / 3600);
    const m = Math.floor((seconds % 3600) / 60);
    const s = Math.floor(seconds % 60);
    const ms = Math.floor((seconds % 1) * 1000);
    return `${String(h).padStart(2, '0')}:${String(m).padStart(2, '0')}:${String(s).padStart(2, '0')}.${String(ms).padStart(3, '0')}`;
  },

  parseSRTTime(timeStr) {
    const parts = timeStr.replace(',', '.').split(':');
    if (parts.length === 3) {
      return parseFloat(parts[0]) * 3600 + parseFloat(parts[1]) * 60 + parseFloat(parts[2]);
    }
    return 0;
  },

  downloadFile(filename, content, type) {
    const blob = new Blob([content], { type });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = filename;
    document.body.appendChild(a);
    a.click();
    document.body.removeChild(a);
    URL.revokeObjectURL(url);
  }
};
